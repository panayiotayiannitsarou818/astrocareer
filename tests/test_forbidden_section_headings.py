"""Ο έλεγχος απαγορευμένων ενοτήτων (Κανόνας 3.5) πιάνει ΤΙΤΛΟΥΣ, όχι φράσεις.

Περιστατικό: σωστό καθαρό παραδοτέο απορρίφθηκε επειδή μια παράγραφος
ταλέντου περιείχε τη φράση «σχεδιάζεις προσεκτικά τα επόμενα βήματα».
"""
import pytest
from core.validator import _forbidden_section_headings

TITLES = ("Επόμενα βήματα", "Ερωτήσεις για συζήτηση", "Πιθανά εμπόδια", "Next Steps")


@pytest.mark.parametrize("line", [
    "Στην πράξη μπορεί να φαίνεται όταν σχεδιάζεις προσεκτικά τα επόμενα βήματα.",
    "Τα πιθανά εμπόδια σε μια τέτοια πορεία ξεπερνιούνται με εξάσκηση και υπομονή.",
    "Επόμενα βήματα σε αυτή την κατεύθυνση μπορούν να δοκιμαστούν αργότερα, με ηρεμία και χωρίς βιασύνη.",
    "Αξίζει να δοκιμαστεί σε ερωτήσεις για συζήτηση μέσα σε μια ομάδα ανθρώπων που εμπιστεύεσαι.",
    "She plans the next steps carefully before starting.",
])
def test_phrase_inside_sentence_is_not_a_section(line):
    text = "Ταλέντα προς διερεύνηση\n1. Τίτλος\n" + line + "\nΤελική Σύνθεση\nΚείμενο."
    assert _forbidden_section_headings(text, TITLES) == []


@pytest.mark.parametrize("line,expected", [
    ("Επόμενα βήματα", "Επόμενα βήματα"),
    ("5. Επόμενα βήματα", "Επόμενα βήματα"),
    ("Επόμενα βήματα:", "Επόμενα βήματα"),
    ("## Επόμενα Βήματα", "Επόμενα βήματα"),
    ("**Επόμενα βήματα**", "Επόμενα βήματα"),
    ("• Επόμενα βήματα: δοκίμασε μια ομαδική δραστηριότητα.", "Επόμενα βήματα"),
    ("Επόμενα βήματα για τους γονείς", "Επόμενα βήματα"),
    ("ΠΙΘΑΝΑ ΕΜΠΟΔΙΑ".capitalize(), None),  # χωρίς τόνους δεν είναι ο ίδιος τίτλος
    ("Πιθανά εμπόδια", "Πιθανά εμπόδια"),
    ("Ερωτήσεις για συζήτηση", "Ερωτήσεις για συζήτηση"),
    ("Next Steps", "Next Steps"),
])
def test_heading_lines_are_detected(line, expected):
    text = "Τελική Σύνθεση\nΚείμενο.\n" + line + "\nΚάτι ακόμη."
    assert _forbidden_section_headings(text, TITLES) == ([expected] if expected else [])
